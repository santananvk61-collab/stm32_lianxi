/* =====================================================================
 * 字库文件 font.c —— 只有 12x12 一种字号
 * ---------------------------------------------------------------------
 * 这个文件里只放"字模数据"（每个字长什么样），画屏幕的代码在 oled.c。
 * 想加新汉字：往 FontCN12x12 加一行 24 字节，同时往 CN_Unicode 加编码，
 * 顺序一一对应即可，oled.c 一行都不用改。
 *
 * 只有三张表：
 *   FontASCII6x12 —— 英文/数字/半角符号，宽 6、高 12（95 个）
 *   FontCN12x12   —— 汉字，宽 12、高 12（9 个：波特律动温度气压湿）
 *   FontSYM12x12  —— 特殊符号，宽 12、高 12（1 个：℃）
 *
 * 取模格式（三张表统一）：
 *   按"块"存，每块 8 行（正好是 OLED 的一页）；块内逐列存：
 *     第 n 字节 = 第 n 列，bit0 = 这一块的最上面一行
 *   高 12 = 2 块：前一半字节是第 0~7 行，后一半字节是第 8~15 行（只用前 4 行）
 *   所以 6 宽的字模占 12 字节，12 宽的字模占 24 字节。
 *
 * 为什么统一 12x12：
 *   12x12 汉字墨迹在第 1~11 行（上下自带留白），配 16 像素行距时
 *   行与行之间正好空 5 像素，不会糊在一起。
 *   128x64 的屏：一屏 5 行（64/13），每行 10 个汉字或 21 个英文数字。
 * ===================================================================== */

